int daysum(int year, int month, int day) {//计算公历天数和的函数
    int sum = 0;
    for (int i = 1900;i < year;i++) {
        if ((i % 4 == 0 && i % 100 != 0) || i % 400 == 0) {
            sum += 366;
        }
        else sum += 365;
    }
    if ((year % 4 == 0 && year % 100 != 0) || year % 400 == 0) {
        emonth[1] = 29;
    }
    else {
        emonth[1] = 28;
    }
    for (int i = 0;i < month - 1;i++) {
        sum += emonth[i];
    }
    sum += day;
    return sum;
}
